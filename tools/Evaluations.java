import java.io.IOException;
import java.io.Reader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.stream.Collectors;
import java.util.stream.Stream;

import org.yaml.snakeyaml.LoaderOptions;
import org.yaml.snakeyaml.Yaml;
import org.yaml.snakeyaml.constructor.SafeConstructor;

/**
 * Turns the evaluations in src/evaluations/*.yml into AsciiDoc: for each evaluation, a report with the
 * criteria and their weights, the scores, the ranking and the sensitivity scenarios; and, for all of
 * them, attributes.adoc, which the document includes so that its text and its decisions can refer to
 * the results, such as {eval-chat-models-first}. Change a score or a weight, rebuild, and everything
 * that refers to the results follows, like cells in a spreadsheet.
 *
 * Criteria weights are given directly (method: direct) or derived with the Analytic Hierarchy Process
 * from pairwise comparisons (method: ahp). Alternatives are rated against each criterion on a scale,
 * 1 to 5 by default, and ranked by weighted score: AHP's ratings mode.
 *
 * Invalid input fails the build: a missing score, a score off the scale, a missing comparison, or
 * comparisons whose consistency ratio exceeds the limit, 0.10 by default.
 *
 * The build runs it with the JDK's source launcher and SnakeYAML on the class path:
 *
 *     java -cp snakeyaml.jar tools/Evaluations.java src/evaluations target/generated-docs/evaluations
 */
public class Evaluations {

	/** Saaty's random consistency index, by matrix size */
	private static final double[] RANDOM_INDEX = { 0, 0, 0, 0.58, 0.90, 1.12, 1.24, 1.32, 1.41, 1.45, 1.49 };

	record Criterion(String id, String name, String description) {}

	record Alternative(String id, String label, String name, String description, Map<String, Double> scores, Map<String, String> reasons) {}

	record Scenario(String id, String name, Map<String, Double> overrides, Map<String, Double> weights) {}

	record Ranked(Alternative alternative, double score) {}

	public static void main(String[] args) throws IOException {
		Path source = Path.of(args[0]);
		Path target = Path.of(args[1]);
		Files.createDirectories(target);

		List<Path> files;
		try (Stream<Path> list = Files.list(source)) {
			files = list.filter(p -> p.toString().endsWith(".yml")).sorted().toList();
		}

		StringBuilder attributes = new StringBuilder("// Generated by tools/Evaluations.java from src/evaluations; do not edit\n");
		List<String> errors = new ArrayList<>();
		for (Path file : files) {
			String id = file.getFileName().toString().replaceFirst("\\.yml$", "");
			try {
				new Evaluations(id, load(file)).write(target, attributes);
			} catch (IllegalArgumentException e) {
				errors.add(file.getFileName() + ": " + e.getMessage());
			}
		}
		if (!errors.isEmpty()) {
			errors.forEach(System.err::println);
			System.exit(1);
		}
		Files.writeString(target.resolve("attributes.adoc"), attributes, StandardCharsets.UTF_8);
		System.out.println("Evaluations: " + files.size() + " written to " + target);
	}

	@SuppressWarnings("unchecked")
	private static Map<String, Object> load(Path file) throws IOException {
		try (Reader reader = Files.newBufferedReader(file, StandardCharsets.UTF_8)) {
			return (Map<String, Object>) new Yaml(new SafeConstructor(new LoaderOptions())).load(reader);
		}
	}

	private final String id;
	private final String title;
	private final String method;
	private final double min;
	private final double max;
	private final double closeMargin;
	private final double maxConsistencyRatio;
	private final List<Criterion> criteria = new ArrayList<>();
	private final List<Alternative> alternatives = new ArrayList<>();
	private final List<Scenario> scenarios = new ArrayList<>();
	private final Map<String, Double> weights = new LinkedHashMap<>();
	private double[][] comparisons;
	private double consistencyRatio;

	@SuppressWarnings("unchecked")
	Evaluations(String id, Map<String, Object> spec) {
		this.id = id;
		title = string(spec, "title", id);
		method = string(spec, "method", "direct");
		List<Number> scale = (List<Number>) spec.getOrDefault("scale", List.of(1, 5));
		min = scale.get(0).doubleValue();
		max = scale.get(1).doubleValue();
		closeMargin = number(spec.getOrDefault("close-margin", 0.25));
		maxConsistencyRatio = number(spec.getOrDefault("max-consistency-ratio", 0.10));

		for (Map<String, Object> c : (List<Map<String, Object>>) required(spec, "criteria")) {
			criteria.add(new Criterion(string(c, "id", null), string(c, "name", null), string(c, "description", null)));
		}

		switch (method) {
			case "direct" -> {
				Map<String, Object> given = (Map<String, Object>) required(spec, "weights");
				for (Criterion c : criteria) {
					weights.put(c.id(), number(required(given, c.id())));
				}
				normalize(weights);
			}
			case "ahp" -> ahp((Map<String, Map<String, Object>>) required(spec, "comparisons"));
			default -> throw new IllegalArgumentException("method must be direct or ahp, not " + method);
		}

		for (Map<String, Object> a : (List<Map<String, Object>>) required(spec, "alternatives")) {
			String alternativeId = string(a, "id", null);
			Map<String, Object> given = (Map<String, Object>) required(a, "scores");
			Map<String, Double> scores = new LinkedHashMap<>();
			Map<String, String> reasons = new LinkedHashMap<>();
			for (Criterion c : criteria) {
				Object value = given.get(c.id());
				if (value == null) {
					throw new IllegalArgumentException(alternativeId + " has no score for " + c.id());
				}
				if (value instanceof Map<?, ?> scored) {
					reasons.put(c.id(), String.valueOf(scored.get("reason")));
					value = scored.get("score");
				}
				double score = number(value);
				if (score < min || score > max) {
					throw new IllegalArgumentException(alternativeId + "." + c.id() + " = " + score + " is outside " + min + ".." + max);
				}
				scores.put(c.id(), score);
			}
			alternatives.add(new Alternative(alternativeId, string(a, "label", alternativeId), string(a, "name", alternativeId), string(a, "description", null), scores, reasons));
		}

		for (Map<String, Object> s : (List<Map<String, Object>>) spec.getOrDefault("scenarios", List.of())) {
			Map<String, Double> overrides = new LinkedHashMap<>();
			((Map<String, Object>) required(s, "weights")).forEach((k, v) -> overrides.put(criterion(k).id(), number(v)));
			// Overrides are percentages; the criteria not overridden keep their weights
			Map<String, Double> scenarioWeights = new LinkedHashMap<>();
			for (Criterion c : criteria) {
				scenarioWeights.put(c.id(), overrides.containsKey(c.id()) ? overrides.get(c.id()) : weights.get(c.id()) * 100);
			}
			normalize(scenarioWeights);
			scenarios.add(new Scenario(string(s, "id", null), string(s, "name", null), overrides, scenarioWeights));
		}
	}

	/** Weights from the principal eigenvector of the pairwise comparison matrix, and its consistency ratio */
	private void ahp(Map<String, Map<String, Object>> given) {
		int n = criteria.size();
		comparisons = new double[n][n];
		for (int i = 0; i < n; i++) {
			comparisons[i][i] = 1;
			for (int j = i + 1; j < n; j++) {
				String row = criteria.get(i).id();
				String column = criteria.get(j).id();
				Object value = given.getOrDefault(row, Map.of()).get(column);
				if (value == null) {
					throw new IllegalArgumentException("no comparison of " + row + " with " + column);
				}
				double v = number(value);
				if (v < 1.0 / 9 - 1e-9 || v > 9 + 1e-9) {
					throw new IllegalArgumentException(row + " vs " + column + " = " + v + " is outside 1/9..9");
				}
				comparisons[i][j] = v;
				comparisons[j][i] = 1 / v;
			}
		}

		// tag::ahp-weights[]
		double[] w = new double[n];
		java.util.Arrays.fill(w, 1.0 / n);
		for (int iteration = 0; iteration < 1000; iteration++) {
			double[] next = multiply(comparisons, w);
			double sum = java.util.Arrays.stream(next).sum();
			for (int i = 0; i < n; i++) {
				next[i] /= sum;
			}
			double delta = 0;
			for (int i = 0; i < n; i++) {
				delta = Math.max(delta, Math.abs(next[i] - w[i]));
			}
			w = next;
			if (delta < 1e-12) {
				break;
			}
		}
		double[] aw = multiply(comparisons, w);
		double lambda = 0;
		for (int i = 0; i < n; i++) {
			lambda += aw[i] / w[i] / n;
		}
		double ci = n > 2 ? (lambda - n) / (n - 1) : 0;
		consistencyRatio = n > 2 && n < RANDOM_INDEX.length ? ci / RANDOM_INDEX[n] : 0;
		if (consistencyRatio > maxConsistencyRatio) {
			throw new IllegalArgumentException(String.format(Locale.ROOT,
					"the comparisons are inconsistent: consistency ratio %.3f exceeds %.2f", consistencyRatio, maxConsistencyRatio));
		}
		for (int i = 0; i < n; i++) {
			weights.put(criteria.get(i).id(), w[i]);
		}
		// end::ahp-weights[]
	}

	private void write(Path target, StringBuilder attributes) throws IOException {
		List<Ranked> ranking = rank(weights);
		String prefix = "eval-" + id;
		StringBuilder out = new StringBuilder();
		out.append("// Generated by tools/Evaluations.java from src/evaluations/").append(id).append(".yml; do not edit\n\n");

		// Criteria and weights
		out.append("[#").append(prefix).append("-criteria]\n");
		out.append(".").append(title).append(": criteria and weights\n");
		out.append("[cols=\"2,4,1\",options=\"header\"]\n|===\n|Criterion |Description |Weight\n\n");
		for (Criterion c : criteria) {
			out.append("|").append(cell(c.name())).append("\n|").append(cell(c.description())).append("\n|")
					.append(percent(weights.get(c.id()))).append("\n\n");
		}
		out.append("|===\n\n");

		if (comparisons != null) {
			out.append("The weights are derived with the Analytic Hierarchy Process from the pairwise comparisons in <<")
					.append(prefix).append("-comparisons>>. A value of 3 means the criterion of the row is moderately more important than that of the column; 1/3, the reverse. ")
					.append(String.format(Locale.ROOT, "The consistency ratio of the comparisons is %.3f, within the limit of %.2f.%n%n", consistencyRatio, maxConsistencyRatio));
			out.append("[#").append(prefix).append("-comparisons]\n");
			out.append(".").append(title).append(": pairwise comparisons of the criteria\n");
			out.append("[cols=\"3").append(",1".repeat(criteria.size())).append("\",options=\"header\"]\n|===\n|");
			for (int j = 0; j < criteria.size(); j++) {
				out.append(" |").append(j + 1);
			}
			out.append("\n\n");
			for (int i = 0; i < criteria.size(); i++) {
				out.append("|").append(i + 1).append(". ").append(cell(criteria.get(i).name()));
				for (int j = 0; j < criteria.size(); j++) {
					out.append(" |").append(fraction(comparisons[i][j]));
				}
				out.append("\n");
			}
			out.append("|===\n\n");
		}

		// Scores
		out.append("[#").append(prefix).append("-scores]\n");
		out.append(".").append(title).append(": scores from ").append(format(min)).append(" (poor) to ").append(format(max)).append(" (excellent)\n");
		out.append("[cols=\"4,1").append(",1".repeat(alternatives.size())).append("\",options=\"header\"]\n|===\n|Criterion |Weight");
		for (Alternative a : alternatives) {
			out.append(" |").append(cell(a.label()));
		}
		out.append("\n\n");
		for (Criterion c : criteria) {
			out.append("|").append(cell(c.name())).append(" |").append(percent(weights.get(c.id())));
			for (Alternative a : alternatives) {
				out.append(" |").append(format(a.scores().get(c.id())));
			}
			out.append("\n");
		}
		out.append("\n|*Weighted score* |*100%*");
		Map<String, Double> totals = ranking.stream().collect(Collectors.toMap(r -> r.alternative().id(), Ranked::score));
		for (Alternative a : alternatives) {
			out.append(" |*").append(score(totals.get(a.id()))).append("*");
		}
		out.append("\n|===\n\n");

		out.append("Ranking: ").append(rankingText(ranking)).append(".\n\n");
		double margin = ranking.size() > 1 ? round(ranking.get(0).score()) - round(ranking.get(1).score()) : Double.POSITIVE_INFINITY;
		if (margin < closeMargin) {
			out.append("[NOTE]\n====\nA close call: ").append(ranking.get(0).alternative().name()).append(" and ")
					.append(ranking.get(1).alternative().name()).append(" are ").append(score(margin))
					.append(" apart, less than the margin of ").append(score(closeMargin))
					.append(" this evaluation treats as decisive. The ranking alone does not settle the choice.\n====\n\n");
		}

		// Reasons
		if (alternatives.stream().anyMatch(a -> !a.reasons().isEmpty() || a.description() != null)) {
			out.append("[#").append(prefix).append("-reasons]\n");
			out.append(".Alternatives and the reasons for their scores\n");
			for (Alternative a : alternatives) {
				// Not "A. Name", which is an ordered list item, nor "Name (C)", which is a copyright sign
				out.append(cell(a.label())).append(" — ").append(a.name()).append(", ").append(score(totals.get(a.id()))).append("::\n");
				if (a.description() != null) {
					out.append(a.description()).append("\n");
				}
				for (Criterion c : criteria) {
					String reason = a.reasons().get(c.id());
					if (reason != null) {
						out.append("* _").append(c.name()).append("_, ").append(format(a.scores().get(c.id()))).append(": ").append(reason).append("\n");
					}
				}
			}
			out.append("\n");
		}

		// Sensitivity
		if (!scenarios.isEmpty()) {
			out.append("[#").append(prefix).append("-sensitivity]\n");
			out.append(".").append(title).append(": sensitivity of the ranking to the weights\n");
			out.append("[cols=\"2,3,4\",options=\"header\"]\n|===\n|Scenario |Weights changed |Ranking\n\n");
			out.append("|Base |- |").append(rankingText(ranking)).append("\n\n");
			for (Scenario s : scenarios) {
				String changed = s.overrides().entrySet().stream()
						.map(e -> criterion(e.getKey()).name() + ": " + percent(weights.get(e.getKey())) + " → " + percent(s.weights().get(e.getKey())))
						.collect(Collectors.joining(" +\n"));
				out.append("|").append(cell(s.name())).append("\n|").append(cell(changed)).append("\n|").append(rankingText(rank(s.weights()))).append("\n\n");
			}
			out.append("|===\n");
		}
		Files.writeString(target.resolve(id + ".adoc"), out, StandardCharsets.UTF_8);

		// Attributes for the rest of the document
		attributes.append("\n// ").append(title).append("\n");
		attribute(attributes, prefix + "-title", title);
		for (int i = 0; i < Math.min(2, ranking.size()); i++) {
			String place = i == 0 ? "-first" : "-second";
			attribute(attributes, prefix + place + "-id", ranking.get(i).alternative().id());
			attribute(attributes, prefix + place, ranking.get(i).alternative().name());
			attribute(attributes, prefix + place + "-score", score(ranking.get(i).score()));
		}
		if (ranking.size() > 1) {
			attribute(attributes, prefix + "-margin", score(margin));
		}
		if (margin < closeMargin) {
			attribute(attributes, prefix + "-close", "");
		}
		attribute(attributes, prefix + "-ranking", rankingText(ranking));
		if (comparisons != null) {
			attribute(attributes, prefix + "-consistency-ratio", String.format(Locale.ROOT, "%.3f", consistencyRatio));
		}
		for (int i = 0; i < ranking.size(); i++) {
			Ranked r = ranking.get(i);
			attribute(attributes, prefix + "-" + r.alternative().id(), r.alternative().name());
			attribute(attributes, prefix + "-" + r.alternative().id() + "-score", score(r.score()));
			attribute(attributes, prefix + "-" + r.alternative().id() + "-rank", String.valueOf(i + 1));
		}
		for (Criterion c : criteria) {
			attribute(attributes, prefix + "-weight-" + c.id(), percent(weights.get(c.id())));
		}
		for (Scenario s : scenarios) {
			List<Ranked> r = rank(s.weights());
			attribute(attributes, prefix + "-scenario-" + s.id(), s.name());
			attribute(attributes, prefix + "-scenario-" + s.id() + "-first-id", r.get(0).alternative().id());
			attribute(attributes, prefix + "-scenario-" + s.id() + "-first", r.get(0).alternative().name());
			attribute(attributes, prefix + "-scenario-" + s.id() + "-ranking", rankingText(r));
		}
	}

	private List<Ranked> rank(Map<String, Double> w) {
		List<Ranked> ranked = new ArrayList<>();
		for (Alternative a : alternatives) {
			double total = 0;
			for (Criterion c : criteria) {
				total += w.get(c.id()) * a.scores().get(c.id());
			}
			ranked.add(new Ranked(a, total));
		}
		// Stable: alternatives with equal scores keep their order in the file
		ranked.sort(Comparator.comparingDouble((Ranked r) -> round(r.score())).reversed());
		return ranked;
	}

	private Criterion criterion(String criterionId) {
		return criteria.stream().filter(c -> c.id().equals(criterionId)).findFirst()
				.orElseThrow(() -> new IllegalArgumentException("unknown criterion " + criterionId));
	}

	private static String rankingText(List<Ranked> ranking) {
		return ranking.stream().map(r -> r.alternative().label() + " " + score(r.score())).collect(Collectors.joining(", "));
	}

	private static void attribute(StringBuilder attributes, String name, String value) {
		attributes.append(':').append(name).append(':').append(value.isEmpty() ? "" : " " + value).append('\n');
	}

	private static void normalize(Map<String, Double> w) {
		double sum = w.values().stream().mapToDouble(Double::doubleValue).sum();
		if (sum <= 0) {
			throw new IllegalArgumentException("weights must be positive");
		}
		w.replaceAll((k, v) -> v / sum);
	}

	private static double[] multiply(double[][] m, double[] v) {
		double[] result = new double[v.length];
		for (int i = 0; i < v.length; i++) {
			for (int j = 0; j < v.length; j++) {
				result[i] += m[i][j] * v[j];
			}
		}
		return result;
	}

	private static double round(double value) {
		return Math.round(value * 100) / 100.0;
	}

	private static String score(double value) {
		return String.format(Locale.ROOT, "%.2f", value);
	}

	private static String percent(double weight) {
		double p = weight * 100;
		return Math.abs(p - Math.rint(p)) < 0.05 ? String.format(Locale.ROOT, "%.0f%%", p) : String.format(Locale.ROOT, "%.1f%%", p);
	}

	private static String format(double value) {
		return value == Math.rint(value) ? String.valueOf((long) value) : String.valueOf(value);
	}

	private static String fraction(double value) {
		if (value >= 1 - 1e-9) {
			return format(Math.round(value * 100) / 100.0);
		}
		double inverse = 1 / value;
		return Math.abs(inverse - Math.rint(inverse)) < 1e-6 ? "1/" + Math.round(inverse) : String.format(Locale.ROOT, "%.2f", value);
	}

	private static String cell(String text) {
		return text == null ? "" : text.replace("|", "\\|");
	}

	private static Object required(Map<String, Object> map, String key) {
		Object value = map.get(key);
		if (value == null) {
			throw new IllegalArgumentException("missing " + key);
		}
		return value;
	}

	private static String string(Map<String, Object> map, String key, String defaultValue) {
		Object value = map.get(key);
		if (value == null && defaultValue == null && !"description".equals(key)) {
			throw new IllegalArgumentException("missing " + key);
		}
		return value == null ? defaultValue : String.valueOf(value);
	}

	/** A number, or a fraction such as 1/3 */
	private static double number(Object value) {
		if (value instanceof Number n) {
			return n.doubleValue();
		}
		String text = String.valueOf(value).trim();
		int slash = text.indexOf('/');
		return slash < 0 ? Double.parseDouble(text) : Double.parseDouble(text.substring(0, slash)) / Double.parseDouble(text.substring(slash + 1));
	}

}
